def angle(a,b):
 den=a.norm(dim=-1)*b.norm(dim=-1)
 c=(a*b).sum(-1)/den.clamp_min(1e-12)
 c=c.clamp(-1,1); c[den<1e-12]=torch.nan
 return torch.acos(c),1-c

def offsets(tok,text):
 return tok(text,add_special_tokens=False,return_offsets_mapping=True)['offset_mapping']
def span_tokens(off,start,end): return [i for i,(a,b) in enumerate(off) if b>start and a<end]

def render_chat(tok,messages):
 # Some Qwen chat templates strip boundary whitespace. Protect only such content
 # while formatting, then remove sentinels before tokenization; no marker is fed.
 start='__SVG_BOUNDARY_START_91cf__';end='__SVG_BOUNDARY_END_91cf__'
 protected=[]
 for message in messages:
  item=dict(message);content=item['content']
  assert start not in content and end not in content
  if content!=content.strip():item['content']=start+content+end
  protected.append(item)
 prompt=tok.apply_chat_template(protected,tokenize=False,add_generation_prompt=True,enable_thinking=False)
 prompt=prompt.replace(start,'').replace(end,'')
 assert start not in prompt and end not in prompt
 return prompt

@torch.inference_mode()
def run_case(tok,model,case,dream):
 messages=[]
 prime_answer=None; prime_ids=None
 if case.get('prime'):
  first=dream+'\n看着这幅画，不要分析，只要用心感受。你，回忆起了什么？'
  if 'prime_response' in case:
   prime_answer=case['prime_response']; prime_ids=case['prime_response_token_ids']
  else:
   p=render_chat(tok,[dict(role='user',content=first)])
   x=tok(p,return_tensors='pt',add_special_tokens=False).to('cuda')
   y=model.generate(**x,max_new_tokens=case.get('prime_max_new',30),do_sample=False,pad_token_id=tok.eos_token_id)
   prime_ids=y[0,x.input_ids.shape[1]:].tolist()
   prime_answer=tok.decode(prime_ids,skip_special_tokens=True)
  messages=[dict(role='user',content=first),dict(role='assistant',content=prime_answer)]
 messages.append(dict(role='user',content=case['text']))
 prompt=render_chat(tok,messages)+case.get('prefix','')
 ids=tok(prompt,return_tensors='pt',add_special_tokens=False).input_ids.to('cuda')
 n_prompt=ids.shape[1]
 if case['max_new']:
  full=model.generate(ids,max_new_tokens=case['max_new'],do_sample=False,pad_token_id=tok.eos_token_id)
 else: full=ids
 generated=full[0,n_prompt:].tolist()
 # Replay fixed token IDs to capture every temporal point, including the last
 # emitted token. Store replay-vs-cached greedy agreement as a numeric audit.
 hidden=[]
 handles=[model.model.embed_tokens.register_forward_hook(lambda m,a,o:hidden.append(o[0].detach().cpu()))]
 for layer in model.model.layers:
  handles.append(layer.register_forward_hook(lambda m,a,o:hidden.append((o[0] if isinstance(o,tuple) else o)[0].detach().cpu())))
 try: out=model(full,use_cache=False,logits_to_keep=1)
 finally:
  for h in handles: h.remove()
 last_logits=out.logits[0,-1].float(); del out
 L=len(hidden)-1; T=full.shape[1]
 assert len(hidden)==len(model.model.layers)+1
 temporal=[]; onecos=[]; layercurv=[]
 for l in range(1,L+1):
  h=hidden[l].float(); d=h[1:]-h[:-1]; a,b=angle(d[:-1],d[1:])
  temporal.append(torch.cat([torch.full((2,),torch.nan),a]).numpy())
  onecos.append(torch.cat([torch.full((2,),torch.nan),b]).numpy())
  if l<L:
   _,b=angle(h-hidden[l-1].float(),hidden[l+1].float()-h); layercurv.append(b.numpy())
 lens={}
 # Fixed norm lens, not a learned tuned lens. All final positions + 5 intermediate depths.
 lens_layers=sorted(set([1,max(1,round(L*.25)),round(L*.5),round(L*.75),round(L*.85),L]))
 for l in lens_layers:
  ent=[]; top=[]; argmax=[]
  for s in range(0,T,32):
   h=hidden[l][s:s+32].to('cuda'); z=model.lm_head(model.model.norm(h)).float()
   logp=torch.log_softmax(z,dim=-1); p=logp.exp()
   ent.extend((-(p*logp).sum(-1)).cpu().tolist()); top.extend(p.max(-1).values.cpu().tolist())
   argmax.extend(z.argmax(-1).cpu().tolist())
   del z,logp,p,h
  lens[str(l)]={'entropy_nats':ent,'pmax':top,'argmax_token_ids':argmax}
 # Confirm hook's unnormalized final block + final_norm == model output.
 z=model.lm_head(model.model.norm(hidden[-1][-1:].to('cuda')))[0].float()
 logit_max_error=(z-last_logits).abs().max().item()
 assert logit_max_error<0.1,logit_max_error
 off=offsets(tok,prompt)
 content_start=prompt.rfind(case['text']); assert content_start>=0
 content_idx=span_tokens(off,content_start,content_start+len(case['text']))
 special=set(tok.all_special_ids)
 spans={'content':content_idx,'generated':[i for i in range(n_prompt,T) if int(full[0,i]) not in special],'generated_with_special':list(range(n_prompt,T))}
 if 'trigger' in case:
  start=prompt.find(case['trigger'],content_start); assert start>=0
  spans['conflict']=span_tokens(off,start,start+len(case['trigger']))
  start_idx=min(spans['conflict']); spans['pre_conflict']=list(range(max(2,start_idx-3),start_idx))
 if case.get('prefix'):
  begin=len(prompt)-len(case['prefix']); marker=prompt.rfind('答案是：')
  spans['answer_marker']=span_tokens(off,marker,len(prompt))
  spans['answer']=spans['answer_marker']+spans['generated']
  if case.get('rationale'):
   end=prompt.rfind('）'); spans['parenthesis']=span_tokens(off,begin,end+1)
 temp=np.stack(temporal); lc=np.stack(layercurv)
 middle=list(range(math.ceil(.5*L)-1,math.floor(.85*L)))
 k=temp[middle].mean(0); kl=lc[[i for i in middle if i<len(lc)]].mean(0)
 def summary(idx):
  idx=[i for i in idx if i>=2]
  if not idx: return None
  return dict(n=len(idx),temp_rad=float(np.nanmean(k[idx])),temp_one_minus_cos=float(np.nanmean(np.stack(onecos)[middle][:,idx])),layer_one_minus_cos=float(np.nanmean(kl[idx])),entropy_nats=float(np.mean(np.array(lens[str(L)]['entropy_nats'])[idx])),pmax=float(np.mean(np.array(lens[str(L)]['pmax'])[idx])))
 result=dict(**case,prompt=prompt,prime_answer=prime_answer,prime_token_ids=prime_ids,generated_text=tok.decode(generated,skip_special_tokens=True),generated_token_ids=generated,special_token_ids=tok.all_special_ids,prompt_tokens=n_prompt,total_tokens=T,token_ids=full[0].tolist(),tokens=tok.convert_ids_to_tokens(full[0].tolist()),spans=spans,summary={s:summary(idx) for s,idx in spans.items()},temporal_rad=[clean(x) for x in temp],temporal_one_minus_cos=[clean(x) for x in onecos],layer_one_minus_cos=[clean(x) for x in lc],lens=lens,mid_layer_indices_one_based=[i+1 for i in middle],mid_temp_rad=clean(k),mid_layer_one_minus_cos=clean(kl),final_logit_hook_max_error=logit_max_error,memory=mem())
 result['cached_vs_replay_greedy_agreement']=(float(np.mean(np.array(lens[str(L)]['argmax_token_ids'])[n_prompt-1:T-1]==np.array(generated))) if generated else None)
 # Rolling mean of three task-defined turning angles ending at t. Entropy at t
 # predicts t+1; paper's token naming shifts this index by one.
 result['contextual_3angle_rad']=clean(np.convolve(np.nan_to_num(k,nan=0),np.ones(3)/3,'full')[:T]); result['contextual_3angle_rad'][:4]=[None]*min(4,T)
 del hidden,full,ids,last_logits,z
 gc.collect(); torch.cuda.empty_cache()
 return result

def main():
 ap=argparse.ArgumentParser(); ap.add_argument('--model',required=True); ap.add_argument('--limit',type=int); args=ap.parse_args()
 assert torch.cuda.is_available() and 'GB10' in torch.cuda.get_device_name(), 'DGX Spark GPU required'
 torch.set_num_threads(8); torch.manual_seed(0)
 dream=(ROOT/'dream.svg').read_text(); cases=make_cases(dream)
 if args.model=='Qwen3-0.6B': cases=[c for c in cases if not c.get('prime')]
 if args.limit: cases=cases[:args.limit]
 dest=ROOT/'raw'/args.model; dest.mkdir(parents=True,exist_ok=True)
 pending=[c for c in cases if not (dest/(c['id']+'.json')).exists()]
 if not pending:return
 drop(); tok,model=load_model(args.model)
 save(dest/'environment.json',dict(torch=torch.__version__,transformers=__import__('transformers').__version__,python=platform.python_version(),device=torch.cuda.get_device_name(),model=args.model,config=model.config.to_dict(),generation_config=model.generation_config.to_dict(),dtype='BF16; 27B dequantized from official block FP8; text-only',seed=0,memory=mem()))
 for c in pending:
  t=time.time(); print('CASE_START',args.model,c['id'],flush=True)
  r=run_case(tok,model,c,dream); r['seconds']=time.time()-t
  save(dest/(c['id']+'.json'),r); print('CASE_DONE',c['id'],r['seconds'],r['generated_text'],flush=True)
 del model,tok; drop()
if __name__=='__main__':main()
