def load_model(name):
 path='/home/lmxxf/work/models/'+name
 tok=AutoTokenizer.from_pretrained(path)
 if name=='Qwen3-0.6B':
  model=AutoModelForCausalLM.from_pretrained(path,dtype=torch.bfloat16,device_map='cuda',attn_implementation='sdpa').eval()
 else:
  # Instantiate text-only architecture; load one shard at a time, dequantizing each
  # 128x128 FP8 block to BF16. No full CPU state dict or full-model FP8 copy.
  from transformers import Qwen3_5ForCausalLM
  cfg=AutoConfig.from_pretrained(path).text_config
  cfg._attn_implementation='sdpa'
  with torch.device('meta'): model=Qwen3_5ForCausalLM(cfg)
  params=dict(model.named_parameters()); assigned=set()
  for shard in ['outside.safetensors']+[f'layers-{i}.safetensors' for i in range(cfg.num_hidden_layers)]:
   print('LOAD',shard,mem(),flush=True)
   with safe_open(str(Path(path)/shard),framework='pt',device='cuda') as f:
    keys=set(f.keys())
    for key in sorted(keys):
     target=key.replace('model.language_model.','model.')
     if target not in params: continue
     w=f.get_tensor(key)
     if w.dtype in (torch.float8_e4m3fn,torch.float8_e5m2):
      scale_key=key+'_scale_inv'
      assert scale_key in keys,(key,sorted(keys))
      scale=f.get_tensor(scale_key).float()
      w=w.to(torch.bfloat16)
      # Broadcast scales on a block view; no expanded full-size scale tensor.
      if w.shape[0]%128==0 and w.shape[1]%128==0:
       w.view(w.shape[0]//128,128,w.shape[1]//128,128).mul_(scale[:,None,:,None].to(w.dtype))
      else:
       for r in range(0,w.shape[0],128):
        row=scale[r//128].repeat_interleave(128)[:w.shape[1]]
        w[r:r+128].mul_(row.to(w.dtype))
      del scale
     else: w=w.to(dtype=torch.bfloat16)
     parent,leaf=target.rsplit('.',1)
     setattr(model.get_submodule(parent),leaf,torch.nn.Parameter(w,requires_grad=False))
     assigned.add(target)
   drop()
  missing=set(params)-assigned
  assert not missing,missing
  # Rotary buffers are generated by the constructor and must leave meta too.
  from transformers.models.qwen3_5.modeling_qwen3_5 import Qwen3_5TextRotaryEmbedding
  model.model.rotary_emb=Qwen3_5TextRotaryEmbedding(cfg).to('cuda')
  assert not [(n,str(p.shape)) for n,p in model.named_parameters() if p.is_meta]
  model.generation_config.eos_token_id=json.loads((Path(path)/'generation_config.json').read_text())['eos_token_id']
  model.eval()
 print('MODEL_READY',name,torch.cuda.memory_allocated(),mem(),flush=True)
 return tok,model

